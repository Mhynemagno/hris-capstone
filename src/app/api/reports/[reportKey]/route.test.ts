import { describe, expect, it, vi } from "vitest";

const mocks = vi.hoisted(() => ({
  buildReportPdf: vi.fn(() => new Uint8Array([1, 2, 3])),
  getCurrentRole: vi.fn(),
  rpc: vi.fn(),
}));

vi.mock("@/lib/auth/current-role", () => ({ getCurrentRole: mocks.getCurrentRole }));
vi.mock("@/lib/reporting/pdf", () => ({ buildReportPdf: mocks.buildReportPdf }));
vi.mock("@/lib/supabase/server", () => ({ createServerSupabaseClient: async () => ({ rpc: mocks.rpc }) }));

import { GET } from "./route";

const report = {
  reportKey: "deployments",
  title: "Deployments",
  generatedAt: "2026-10-24T03:00:00.000Z",
  columns: [{ key: "employee", label: "Employee" }],
  rows: [{ employee: "SPO2 Maria Santos" }],
  totalCount: 1,
  page: 1,
  pageSize: 100,
};

describe("formal report download", () => {
  it("identifies an HR-generated PDF as generated by HR Admin", async () => {
    mocks.getCurrentRole.mockResolvedValue("hr_personnel");
    mocks.rpc.mockResolvedValue({ data: report, error: null });

    const response = await GET(new Request("http://localhost/api/reports/deployments.pdf"), {
      params: Promise.resolve({ reportKey: "deployments.pdf" }),
    });

    expect(response.status).toBe(200);
    expect(mocks.buildReportPdf).toHaveBeenCalledWith(expect.objectContaining({ reportKey: "deployments", rows: report.rows }), "HR Admin");
  });
});
